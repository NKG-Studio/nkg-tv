"""Train TinySR2: original synthetic-only 9→24 ReLU→4 residual subpixel model.
No downloaded images or third-party weights. Deterministic seed and held-out split.
This deliberately tiny proof of integration is NOT Real-ESRGAN or film restoration.
"""
from pathlib import Path
import json, hashlib
import numpy as np
ROOT = Path(__file__).resolve().parents[1]
rng = np.random.default_rng(20261012)

def data(count, seed):
    r=np.random.default_rng(seed); inputs=[]; targets=[]
    yy,xx=np.mgrid[:64,:64].astype(np.float32)
    for _ in range(count):
        a=r.uniform(.02,.4); angle=r.uniform(0,6.28)
        img=.5+.25*np.sin(a*(xx*np.cos(angle)+yy*np.sin(angle))+r.uniform(0,6.28))
        for k in range(5):
            x,y=r.uniform(0,64,2); size=r.uniform(3,20)
            mask=(xx-x)**2+(yy-y)**2<size*size
            img[mask]=r.uniform(.05,.95)
        img=np.clip(img,0,1).astype(np.float32)
        lo=img.reshape(32,2,32,2).mean((1,3))
        patches=np.lib.stride_tricks.sliding_window_view(np.pad(lo,1,mode='edge'),(3,3)).reshape(-1,9)
        hi=img.reshape(32,2,32,2).transpose(0,2,1,3).reshape(-1,4)
        inputs.append(patches-.5); targets.append(hi-lo.reshape(-1,1))
    return np.concatenate(inputs),np.concatenate(targets)
x,y=data(160,1); xt,yt=data(24,2)
w1=rng.normal(0,.25,(9,24)).astype(np.float32); b1=np.full(24,.05,np.float32)
w2=rng.normal(0,.02,(24,4)).astype(np.float32); b2=np.zeros(4,np.float32)
params=[w1,b1,w2,b2]; m=[np.zeros_like(p) for p in params]; v=[np.zeros_like(p) for p in params]
for t in range(1,3001):
    idx=rng.integers(0,len(x),512); xb=x[idx]; yb=y[idx]
    h=np.maximum(xb@w1+b1,0); err=(h@w2+b2-yb); d=err*(2/err.size)
    dh=(d@w2.T)*(h>0)
    grads=[xb.T@dh,dh.sum(0),h.T@d,d.sum(0)]
    for p,g,mi,vi in zip(params,grads,m,v):
        mi[:]=.9*mi+.1*g; vi[:]=.999*vi+.001*g*g
        p[:]-=.002*(mi/(1-.9**t))/(np.sqrt(vi/(1-.999**t))+1e-8)
pred=np.maximum(xt@w1+b1,0)@w2+b2
mse=float(np.mean((pred-yt)**2)); baseline=float(np.mean(yt**2))
metrics={'model':'TinySR2 synthetic preview','architecture':'3x3x1 -> 24 ReLU -> 4 residual subpixels, channel independent', 'training_seed':20261012,'training_images':160,'validation_images':24,'iterations':3000,'heldout_mse':mse,'nearest_mse':baseline,'heldout_psnr_db':float(-10*np.log10(mse)),'nearest_psnr_db':float(-10*np.log10(baseline)), 'scope':'synthetic validation only, no claim on film quality or temporal stability'}
weights={k:a.tolist() for k,a in zip(['w1','b1','w2','b2'],params)}
(ROOT/'app/src/main/assets/tinysr2.json').write_text(json.dumps(weights))
with (ROOT/'core/src/weights.rs').open('w') as f:
    f.write('// Preserve trained float32 weights exactly.\n#![allow(clippy::excessive_precision)]\n')
    f.write('// Generated by tools/train_sr.py; original synthetic-data model.\n')
    for k,a in zip(['W1','B1','W2','B2'],params):
        f.write('pub const '+k+': [f32; '+str(a.size)+'] = ['+','.join(f'{n:.9e}f32' for n in a.flat)+'];\n')
metrics['weights_sha256']=hashlib.sha256((ROOT/'app/src/main/assets/tinysr2.json').read_bytes()).hexdigest()
(ROOT/'docs/model-metrics.json').write_text(json.dumps(metrics,indent=2)+'\n')
print(json.dumps(metrics,indent=2))
